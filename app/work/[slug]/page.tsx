/*
  A case study — one project, all the way through.

  Three blocks are gated on real content and render NOTHING while it is
  missing: the problem, the result tiles, and the owner quote. That is the
  same gate the pricing testimonial uses, and it exists for the same reason:
  this is the easiest page on the site to get caught inventing a number on.
  See the comment above `caseStudies` in lib/content.ts.

  Note what is NOT here: `overflow-hidden` on the "What I built" section.
  BuildScroller pins its screen with `position: sticky`, which silently stops
  working inside a clipped ancestor.
*/

export function generateStaticParams() {
  return caseStudies.map((cs) => ({ slug: cs.slug }));
}

/* Every study is known at build time, so anything else is a 404 rather than
   an empty shell. */
export const dynamicParams = false;

type Props = { params: Promise<{ slug: string }> };

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { slug } = await params;
  const cs = caseStudies.find((c) => c.slug === slug);
  if (!cs) return {};
  return pageMeta({
    // Bare title — the root layout appends " · M Studio".
    title: `${cs.title} — case study`,
    description: cs.outcome,
    path: `/work/${cs.slug}`,
  });
}

const host = (url: string) => url.replace(/^https?:\/\//, "").replace(/\/$/, "");

export default async function CaseStudyPage({ params }: Props) {
  const { slug } = await params;
  const cs = caseStudies.find((c) => c.slug === slug);
  if (!cs) notFound();
  /* Generated by `npm run measure`; undefined renders no block. */
  const scores = measured[cs.slug];
  /*
    CSP nonce, same source as the root layout's. script-src dropped
    'unsafe-inline' for a per-request nonce, so an inline block we write
    ourselves needs one. The root layout already reads headers(), so every
    route under it renders per-request and this costs no static generation
    that wasn't already given up. suppressHydrationWarning for the same
    reason it is on the layout's scripts: the browser redacts the nonce
    value from the DOM once it has applied it, so the client always sees
    nonce="".
  */
  const nonce = (await headers()).get("x-nonce") ?? undefined;

  return (
    <>
      {/*
        This page's own structured data: the WebPage, what it is about, and
        the breadcrumb. The CreativeWork it points at is defined once in the
        sitewide graph, so this references it by `@id` instead of restating
        it and risking the two drifting apart.
      */}
      <script
        nonce={nonce}
        suppressHydrationWarning
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(caseStudyGraph(cs)) }}
      />
      {/*
        V2 pass. The homepage cards land here, so before this a visitor left
        the near-black panel and arrived somewhere that looked like a
        different site. That jump is most of what this conversion is for.

        A wrapper, not a rewrite: `.cp` redefines --color-base, --color-ink,
        --color-muted, --color-line and --section-alt-bg inside its own
        scope, so this page's sections, BuildScroller and WorkflowDemo take
        the V2 palette untouched. Typography is deliberately left alone; see
        the note on the h1 in app/services/page.tsx.

        `current` is not set: /work/[slug] is not one of PanelHeader's five
        links, so there is no nav item to mark, and passing the slug would
        match nothing.
      */}
      <div className="cp">
      {/*
        `relative`, and deliberately NOT `overflow-hidden`.

        BuildScroller pins its screenshot with `position: sticky`, and a
        clipped ancestor becomes the sticky element's scroll container, so the
        screen scrolls away instead of staying put while the build steps go
        past. The warning is in BuildScroller's own header and was already in
        the comment above this function, and the first cut of this conversion
        put overflow-hidden here anyway: measured, the pinned screen moved
        from 1607px to 731px under a 1200px scroll rather than holding near
        96px, with this div named as the nearest clipping ancestor.

        Nothing is lost by dropping it: the aurora lobes are clipped by their
        own `absolute inset-0 overflow-hidden` layer just below, which is
        what keeps them from widening the page.
      */}
      <div className="relative">
        <div aria-hidden="true" className="pointer-events-none absolute inset-0 overflow-hidden">
          <span className="cp-aurora cp-a1" />
          <span className="cp-aurora cp-a2" />
        </div>

        <div className="relative z-10">
          <PanelHeader bookHref="/?offer=call#contact" />
        </div>

        {/* No pt-16: that cleared the fixed <Nav>, and PanelHeader is in flow. */}
        <main className="relative z-10">
        {/* Title + the live link */}
        <section className="border-b border-[var(--cp-line)] bg-[var(--section-alt-bg)] py-14 md:py-20">
          <div className="mx-auto max-w-6xl px-6">
            <Link
              href="/#work"
              className="inline-flex items-center gap-1.5 text-sm text-muted transition-colors hover:text-ink"
            >
              <span aria-hidden="true">←</span> All work
            </Link>
            <p className="mt-8 text-xs text-faint">{cs.tag}</p>
            <div className="mt-2 flex flex-wrap items-end justify-between gap-6">
              <h1 className="display max-w-3xl text-balance text-[2rem] text-ink sm:text-4xl md:text-5xl">
                {cs.title}
              </h1>
              {cs.url && (
                <a
                  href={cs.url}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="inline-flex items-center gap-2 rounded-full border border-signal/50 px-5 py-2.5 text-sm font-semibold text-signal transition-colors hover:bg-signal/10"
                >
                  Visit {host(cs.url)}
                  <span aria-hidden="true">↗</span>
                </a>
              )}
            </div>
            <p className="mt-5 max-w-[62ch] text-[1.0625rem] leading-relaxed text-muted">
              {cs.outcome}
            </p>
            {/* What she owned. The first thing anyone assessing the work
                needs, and the thing a screenshot cannot say. */}
            {cs.role && (
              <p className="mt-6 max-w-[62ch] border-l-2 border-signal/50 pl-4 text-sm leading-relaxed text-ink">
                <span className="font-semibold">My role. </span>
                {cs.role}
              </p>
            )}
          </div>
        </section>

        {/* Hero capture */}
        <section className="py-12 md:py-16">
          <div className="mx-auto max-w-6xl px-6">
            <div className="overflow-hidden rounded-2xl border border-line bg-base shadow-[0_30px_80px_-40px_rgba(11,23,34,0.45)]">
              <div className="relative aspect-[16/10]">
                <Image
                  src={cs.hero.src}
                  alt={cs.hero.alt}
                  fill
                  sizes="(min-width: 1152px) 1104px, 100vw"
                  priority
                  className="object-cover object-top"
                />
              </div>
            </div>
          </div>
        </section>

        {/* The problem — renders nothing until Meg writes it. */}
        {cs.problem && (
          <section className="border-t border-line py-16 md:py-20">
            <div className="mx-auto max-w-6xl px-6">
              <h2 className="display text-2xl text-ink sm:text-3xl">
                The problem
              </h2>
              <p className="mt-5 max-w-[62ch] text-[1.0625rem] leading-relaxed text-muted">
                {cs.problem}
              </p>
            </div>
          </section>
        )}

        {/* What I built. No overflow-hidden on this section — see the note above. */}
        <section className="border-t border-line py-16 md:py-20">
          <div className="mx-auto max-w-6xl px-6">
            <h2 className="display text-2xl text-ink sm:text-3xl md:text-4xl">
              What I built
            </h2>
            <div className="mt-10">
              <BuildScroller items={cs.built} />
            </div>
          </div>
        </section>

        {/* How the work ran. Phases with no body yet are skipped, so a
            half-written process shows only the part that is real. */}
        {cs.process.filter((x) => x.body).length > 0 && (
          <section className="border-t border-line py-16 md:py-20">
            <div className="mx-auto max-w-6xl px-6">
              <h2 className="display-serif text-2xl text-ink sm:text-3xl">
                How it ran
              </h2>
              <ol className="mt-8 grid gap-8 sm:grid-cols-2 lg:grid-cols-4">
                {cs.process
                  .filter((x) => x.body)
                  .map((x, i) => (
                    <li key={x.phase}>
                      <p className="font-mono text-xs text-signal tabular-nums">
                        {String(i + 1).padStart(2, "0")}
                      </p>
                      <h3 className="display mt-2 text-lg text-ink">
                        {x.phase}
                      </h3>
                      <p className="mt-2 text-sm leading-relaxed text-muted">
                        {x.body}
                      </p>
                    </li>
                  ))}
              </ol>
            </div>
          </section>
        )}

        {/* Measured, not claimed. Generated by `npm run measure` against the
            live URL; the date and tool render alongside so a reader can
            reproduce the run rather than take the numbers on faith. */}
        {scores && (
          <section className="border-t border-line py-16 md:py-20">
            <div className="mx-auto max-w-6xl px-6">
              <h2 className="display-serif text-2xl text-ink sm:text-3xl">
                Measured
              </h2>
              <p className="mt-4 max-w-[62ch] text-sm leading-relaxed text-muted">
                {scores.tool}, run against{" "}
                {host(scores.url)} on{" "}
                {new Date(scores.when).toLocaleDateString("en-US", {
                  year: "numeric",
                  month: "long",
                  day: "numeric",
                })}
                . Run it yourself and you should get the same shape.
              </p>
              <dl className="mt-8 grid grid-cols-2 gap-x-6 gap-y-8 sm:grid-cols-4">
                {[
                  ["Performance", scores.performance],
                  ["Accessibility", scores.accessibility],
                  ["Best practices", scores.bestPractices],
                  ["SEO", scores.seo],
                ].map(([label, score]) => (
                  <div key={label as string}>
                    <dt className="display text-2xl text-ink sm:text-3xl tabular-nums">
                      {score as number}
                    </dt>
                    <dd className="mt-1.5 text-xs leading-snug text-faint">
                      {label as string}
                    </dd>
                  </div>
                ))}
              </dl>
            </div>
          </section>
        )}

        {/* How it works — skipped when there is no flow to show. */}
        {cs.flow.length > 0 && (
          <section className="border-t border-line py-16 md:py-20">
            <div className="mx-auto max-w-6xl px-6">
              <h2 className="display text-2xl text-ink sm:text-3xl">
                How it works
              </h2>
              <div className="mt-8">
                <WorkflowDemo stages={cs.flow} />
              </div>
            </div>
          </section>
        )}

        {/*
          Built with.

          This used to sit here, between "How it works" and "Result", as a
          full section with an h2 the same size as "What I built" — so the
          last thing a visitor read before the outcome was a row of framework
          names. For somebody deciding whether to buy this, that is the least
          useful block on the page, and it was weighted like one of the most.

          It is not deleted, because the stack is a real promise about what a
          client inherits and its absence reads as evasive (see the note above
          `stackColumns` in lib/content.ts). It moved below the result and the
          owner's words, and it is a labelled line rather than a section, so
          the people who come looking for it still find it and nobody else
          has to read past it. The full breakdown is on /about.
        */}

        {/* Result — REAL numbers only, so this is empty today and renders
            nothing. Do not fill it in to make the page look finished. */}
        {cs.results.length > 0 && (
          <section className="border-t border-line py-16 md:py-20">
            <div className="mx-auto max-w-6xl px-6">
              <h2 className="display text-2xl text-ink sm:text-3xl">Result</h2>
              <dl className="mt-8 grid grid-cols-2 gap-x-6 gap-y-8 sm:grid-cols-4">
                {cs.results.map((r) => (
                  <div key={r.label}>
                    <dt className="display text-2xl text-ink sm:text-3xl">
                      {r.value}
                    </dt>
                    <dd className="mt-1.5 text-xs leading-snug text-faint">
                      {r.label}
                      {r.attribution ? ` · ${r.attribution}` : ""}
                    </dd>
                  </div>
                ))}
              </dl>
            </div>
          </section>
        )}

        {/* The owner's words — same gate as the pricing testimonial. */}
        {cs.quote.quote && (
          <section className="border-t border-line py-16 md:py-20">
            <div className="mx-auto max-w-6xl px-6">
              <figure className="rounded-2xl border border-gold/30 bg-gold/[0.05] p-6 md:p-8">
                <blockquote className="max-w-[62ch] text-lg leading-relaxed text-ink">
                  &ldquo;{cs.quote.quote}&rdquo;
                </blockquote>
                <figcaption className="mt-4 text-xs text-faint">
                  — {cs.quote.name}
                  {cs.quote.business ? ` · ${cs.quote.business}` : ""}
                </figcaption>
              </figure>
            </div>
          </section>
        )}

        <section className="border-t border-line py-10 md:py-12">
          <div className="mx-auto max-w-6xl px-6">
            <h2 className="text-xs font-semibold uppercase tracking-wider text-faint">
              Built with
            </h2>
            <div className="mt-4 flex flex-wrap gap-2">
              {cs.stack.map((t) => (
                <span
                  key={t}
                  className="rounded-full border border-line bg-surface px-3 py-1 text-xs text-muted"
                >
                  {t}
                </span>
              ))}
            </div>
          </div>
        </section>

        {/* Next. OfferLink can't be used off the homepage (it hardcodes
            href="#contact"), so this uses the documented deep link, which
            Contact picks up on load. */}
        <section className="border-t border-line bg-[var(--section-alt-bg)] py-16 md:py-24">
          <div className="mx-auto max-w-6xl px-6">
            <h2 className="display text-2xl text-ink sm:text-3xl md:text-4xl">
              Want something like this?
            </h2>
            <p className="mt-4 max-w-[62ch] text-[1.0625rem] leading-relaxed text-muted">
              Tell me what you are trying to solve. You don&apos;t need a
              technical plan to get started.
            </p>
            <Link
              href="/?offer=custom#contact"
              className="mt-8 inline-flex items-center gap-2 rounded-full bg-signal px-7 py-3.5 text-sm font-semibold text-white transition-transform hover:-translate-y-0.5 active:scale-[0.97]"
            >
              Start a project
              <span aria-hidden="true">→</span>
            </Link>
          </div>
        </section>
        </main>
      </div>
      <Footer />
      <CommandPalette />
      </div>
    </>
  );
}
