/*
  Measures the live sites with Lighthouse and writes lib/measured.ts.

  The scores on a case study have to be real or they are worth less than
  nothing — a number a reader can check and find wrong is worse than no
  number. So they are generated here and never typed by hand: run
  `npm run measure`, commit what it writes.

  Needs Chrome. CHROME_PATH is honoured if set; otherwise this looks for the
  Playwright Chromium the repo already uses for smoke tests.

  Usage:  npm run measure            # every URL below
          npm run measure -- linx    # one slug
*/
import { writeFileSync, existsSync, readdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join } from "node:path";

/* slug -> the live URL its case study links to. */
const TARGETS = {
  "maine-cleaning-co": "https://maineclean.co",
  linx: "https://linx-production-6edf.up.railway.app",
  "the-remote-admin": "https://the-remote-admin.com",
};

function findChrome() {
  if (process.env.CHROME_PATH) return process.env.CHROME_PATH;
  const root = "/opt/pw-browsers";
  if (!existsSync(root)) return null;
  for (const dir of readdirSync(root)) {
    const p = join(root, dir, "chrome-linux", "chrome");
    if (existsSync(p)) return p;
  }
  return null;
}

const only = process.argv.slice(2).filter((a) => !a.startsWith("-"));
const chrome = findChrome();
if (!chrome) {
  console.error("No Chrome found. Set CHROME_PATH and try again.");
  process.exit(1);
}

const out = {};
for (const [slug, url] of Object.entries(TARGETS)) {
  if (only.length && !only.includes(slug)) continue;
  process.stderr.write(`measuring ${slug} … `);
  const tmp = join(process.env.TMPDIR || "/tmp", `lh-${slug}.json`);
  execFileSync(
    "npx",
    [
      "lighthouse", url,
      "--quiet", "--output=json", `--output-path=${tmp}`,
      "--only-categories=performance,accessibility,best-practices,seo",
      "--form-factor=mobile", "--screenEmulation.mobile",
      "--chrome-flags=--headless=new --no-sandbox --disable-dev-shm-usage",
      "--max-wait-for-load=60000",
    ],
    { env: { ...process.env, CHROME_PATH: chrome }, stdio: ["ignore", "ignore", "ignore"] },
  );
  const r = JSON.parse(execFileSync("cat", [tmp], { encoding: "utf8" }));
  const c = r.categories;
  const pct = (x) => Math.round(x.score * 100);
  out[slug] = {
    url,
    when: r.fetchTime,
    tool: `Lighthouse ${r.lighthouseVersion} · mobile`,
    performance: pct(c.performance),
    accessibility: pct(c.accessibility),
    bestPractices: pct(c["best-practices"]),
    seo: pct(c.seo),
  };
  process.stderr.write(
    `perf ${out[slug].performance} · a11y ${out[slug].accessibility} · bp ${out[slug].bestPractices} · seo ${out[slug].seo}\n`,
  );
}

const body = `/*
  GENERATED by \`npm run measure\` — do not edit by hand.

  Real Lighthouse runs against the live sites. Every case study that has an
  entry here renders a "Measured" block with the date and the tool version
  beside the scores, so a reader can reproduce the run instead of trusting it.

  A slug with no entry renders no block at all.
*/
import type { CaseStudyMeasured } from "./content";

export const measured: Record<string, CaseStudyMeasured> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync("lib/measured.ts", body);
console.error(`\nwrote lib/measured.ts (${Object.keys(out).length} site(s))`);
